export function getBrandById(id: string): Brand | undefined {
  return brands.find((b) => b.id === id);
}

export function getBrandsByCategory(category: string): Brand[] {
  return brands.filter((b) => b.category === category);
}

export function searchBrands(query: string): Brand[] {
  const q = query.toLowerCase();
  return brands.filter(
    (b) =>
      b.name.toLowerCase().includes(q) ||
      b.parentCompany?.toLowerCase().includes(q) ||
      b.category.toLowerCase().includes(q)
  );
}

export function getAlternatives(ids: string[]): Brand[] {
  return ids.map((id) => brands.find((b) => b.id === id)).filter(Boolean) as Brand[];
}

